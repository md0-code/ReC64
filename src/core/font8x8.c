void rc_font8x8_build(uint8_t font[2048]) {
    static const uint8_t box[8] = {0x00, 0x7E, 0x42, 0x42, 0x42, 0x42, 0x7E, 0x00};
    for (unsigned c = 0; c < 256; ++c) {
        for (unsigned row = 0; row < 8; ++row) {
            uint8_t bits = box[row];
            if (c >= 0x20 && c < 0x80) bits = rc_font8x8_ascii[c - 0x20][row];
            else if (c >= 0x80 && c < 0x90) {
                /* Block graphics: bit 0 the top right quarter, 1 the top left, 2 the bottom right, 3 the bottom left. */
                const unsigned q = c & 15u, top = row < 4;
                bits = (uint8_t)((q >> (top ? 1 : 3) & 1u ? 0xF0 : 0) | (q >> (top ? 0 : 2) & 1u ? 0x0F : 0));
            } else if (c == 0x00 || c == 0xFF) bits = 0x00;
            else if (c == 0xDB) bits = 0xFF;
            font[c * 8 + row] = bits;
        }
    }
    for (unsigned i = 0; i < sizeof MORE / sizeof *MORE; ++i)
        for (unsigned row = 0; row < 8; ++row) font[MORE[i].code * 8 + row] = MORE[i].rows[row];
}
