"""Embed the existing transparent wordmark for the About screen (Pillow)."""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
image = Image.open(ROOT / 'assets/rec64-datasette-keys.png').convert('RGBA')
width = round(320 / 3)
height = round(image.height * width / image.width)
image = image.resize((width, height), Image.Resampling.LANCZOS).quantize(240, Image.Quantize.FASTOCTREE)
rgba = image.getpalette('RGBA')
colors = [rgba[i:i+4] for i in range(0, 240*4, 4)]
pixels = image.tobytes()
lines = ['/* Generated by tools/embed_about.py from the ReC64 Datasette wordmark. */',
         '#ifndef RC_ABOUT_LOGO_H', '#define RC_ABOUT_LOGO_H',
         f'#define RC_ABOUT_W {width}u', f'#define RC_ABOUT_H {height}u',
         'static const uint32_t RC_ABOUT_COLORS[240]={']
for at in range(0, 240, 8):
    lines.append(','.join(f'0x{a:02x}{r:02x}{g:02x}{b:02x}u' for r,g,b,a in colors[at:at+8])+',')
lines.append('};\nstatic const uint8_t RC_ABOUT_PIXELS[RC_ABOUT_W*RC_ABOUT_H]={')
for at in range(0, len(pixels), 32):
    lines.append(','.join(str(i) for i in pixels[at:at+32])+',')
lines.append('};\n#endif\n')
(ROOT / 'src/app/about_logo.h').write_text('\n'.join(lines), encoding='ascii', newline='\n')
