"""The program's icon from its keys logo (Pillow).

    python tools/embed_icon.py

Writes assets/rec64.ico (16 to 256 pixels; the Windows executable's icon,
tools/build.ps1 links it through the resource CMake generates) and
src/app/rec64_icon.h (64 x 64 ARGB; the window icon on the other platforms,
where an executable has none). The logo is cropped to what it draws and
centred on a transparent square; every size is resampled from it with
premultiplied alpha, so no dark fringe rings the edges.
"""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'assets' / 'rec64-datasette-keys.png'
ICO = ROOT / 'assets' / 'rec64.ico'
HEADER = ROOT / 'src' / 'app' / 'rec64_icon.h'
PREFIX = 'RC_ICON'
SIZES = [16, 20, 24, 32, 40, 48, 64, 128, 256]
WINDOW = 64


def square_logo() -> Image.Image:
    logo = Image.open(SOURCE).convert('RGBA')
    # The drawing's extent: faint specks of the artwork's anti-aliasing do not count.
    logo = logo.crop(logo.getchannel('A').point(lambda a: 255 if a > 64 else 0).getbbox())
    side = max(logo.size)
    square = Image.new('RGBA', (side, side), (0, 0, 0, 0))
    square.paste(logo, ((side - logo.width) // 2, (side - logo.height) // 2))
    return square


def resized(image: Image.Image, size: int) -> Image.Image:
    return image.convert('RGBa').resize((size, size), Image.Resampling.LANCZOS).convert('RGBA')


def main() -> None:
    square = square_logo()
    frames = [resized(square, s) for s in SIZES]
    frames[-1].save(ICO, format='ICO', sizes=[(s, s) for s in SIZES], append_images=frames[:-1])
    raw = resized(square, WINDOW).tobytes()
    words = [f'0x{raw[at + 3]:02x}{raw[at]:02x}{raw[at + 1]:02x}{raw[at + 2]:02x}u' for at in range(0, len(raw), 4)]
    lines = [f'/* Generated by tools/embed_icon.py from {SOURCE.relative_to(ROOT).as_posix()}. */',
             f'#ifndef {PREFIX}_H', f'#define {PREFIX}_H', f'#define {PREFIX}_SIZE {WINDOW}',
             f'static const uint32_t {PREFIX}_ARGB[{PREFIX}_SIZE * {PREFIX}_SIZE] = {{']
    lines += [','.join(words[at:at + 8]) + ',' for at in range(0, len(words), 8)]
    lines += ['};', '#endif', '']
    HEADER.write_text('\n'.join(lines), encoding='ascii', newline='\n')
    print(f'{ICO.relative_to(ROOT).as_posix()}: {", ".join(map(str, SIZES))}; '
          f'{HEADER.relative_to(ROOT).as_posix()}: {WINDOW} x {WINDOW}')


if __name__ == '__main__':
    main()
